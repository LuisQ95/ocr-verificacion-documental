def _palabras_validas(texto):
    """Texto transliterado si es un nombre válido (2 a 28 caracteres, empieza y termina en letra); si no, None."""
    t = transliterar(texto.replace("_", " "))
    return t if 2 <= len(t) <= 28 and \
        re.fullmatch(r"[A-ZÁÉÍÓÚÜÑ][A-ZÁÉÍÓÚÜÑ' -]*[A-ZÁÉÍÓÚÜÑ]", t) else None


def _lista(reales, n, generador, origenes, rnd):
    """Reales (de todos los orígenes) + generados repartidos entre los orígenes, únicos, hasta n."""
    vistos, out = set(), []
    for origen, texto in reales.items():
        for w in texto.split():
            t = _palabras_validas(w)
            if t and t not in vistos:
                vistos.add(t)
                out.append((t, origen, "real"))
    intentos = 0
    while len(out) < n and intentos < n * 200:
        intentos += 1
        origen = origenes[intentos % len(origenes)]
        t = _palabras_validas(generador(rnd, origen))
        if t and t not in vistos and max(len(x) for x in t.split()) <= 18:
            vistos.add(t)
            out.append((t, origen, "generado"))
    rnd.shuffle(out)
    return out[:n] if len(out) >= n else out


def construir(semilla=SEMILLA, vocabulario_anterior=(), reservar=()):
    """Devuelve {nombres_training, nombres_testing, apellidos_training, apellidos_testing, ...} (listas de texto).
    vocabulario_anterior: palabras ya vistas por el modelo actual (van siempre a training).
    reservar: palabras que deben quedar solo para la prueba (p. ej. de documentos reales); se agregan aunque no
    estén en las listas."""
    rnd = random.Random(semilla)
    anterior = {transliterar(w) for w in vocabulario_anterior}
    reservadas = {transliterar(w) for w in reservar}
    out = {}
    for clave, reales, n, gen, origenes in (
            ("nombres", NOMBRES_REALES, N_NOMBRES, _generar_nombre, ORIGENES_GEN_NOMBRE),
            ("apellidos", APELLIDOS_REALES, N_APELLIDOS, _generar_apellido, ORIGENES_GEN_APELLIDO)):
        items = _lista(reales, n, gen, origenes, rnd)
        for w in sorted(reservadas):
            if w not in {t for t, _, _ in items}:
                items[-1] = (w, "reservada", "real")
                rnd.shuffle(items)
        n_prueba = round(len(items) * FRACCION_PRUEBA)
        def palabras(t):
            """Palabras de un nombre compuesto."""
            return set(re.split(r"[ '-]", t))

        candidatos = [it for it in items if not palabras(it[0]) & anterior]
        prueba = [it for it in candidatos if it[0] in reservadas]
        resto = [it for it in candidatos if it[0] not in reservadas]
        prueba += resto[:max(0, n_prueba - len(prueba))]
        en_prueba = {t for t, _, _ in prueba}
        entrenamiento = [it for it in items if it[0] not in en_prueba]
        out[f"{clave}_training"] = sorted(t for t, _, _ in entrenamiento)
        out[f"{clave}_testing"] = sorted(t for t, _, _ in prueba)
        out[f"{clave}_origen"] = {t: f"{o}/{tipo}" for t, o, tipo in items}
    return out


def _apellidos_documentos_reales(raiz, anterior):
    """Apellidos de las personas de los documentos reales, para reservarlos solo para la prueba.

    Se leen de las carpetas de la demo local (`DATOS REALES/demo/postulant_files/<NOMBRES APELLIDOS>`, que no se
    versiona): las dos últimas palabras, salvo las que ya estaban en el vocabulario anterior.
    """
    demo = raiz / "DATOS REALES" / "demo" / "postulant_files"
    if not demo.exists():
        return []
    anterior = {transliterar(w) for w in anterior}
    return sorted({w for d in demo.iterdir() if d.is_dir() for w in d.name.split()[-2:]
                   if transliterar(w) not in anterior})


