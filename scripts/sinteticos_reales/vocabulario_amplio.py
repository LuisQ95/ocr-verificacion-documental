def transliterar(texto):
    """Al alfabeto del modelo: se conservan A-Z, Á É Í Ó Ú Ü Ñ, apóstrofo, guion y espacio."""
    especiales = {"ß": "SS", "Ø": "O", "Æ": "AE", "Œ": "OE", "Ł": "L", "Đ": "D", "Þ": "TH", "Ð": "D",
                  "İ": "I", "I": "I"}
    out = []
    for ch in unicodedata.normalize("NFC", texto.upper()):
        if ch in "ÁÉÍÓÚÜÑ'- " or "A" <= ch <= "Z":
            out.append(ch)
        elif ch in especiales:
            out.append(especiales[ch])
        else:
            base = "".join(c for c in unicodedata.normalize("NFD", ch) if unicodedata.category(c) != "Mn")
            out.append(base if base and all("A" <= c <= "Z" for c in base) else "")
    t = re.sub(r"\s+", " ", "".join(out)).strip(" -'")
    return re.sub(r"-{2,}", "-", t)


def _acentuar(p, rnd):
    """Acento ortográfico típico del español en apellidos generados: BENITEZ -> BENÍTEZ, CALDERON ya trae ÓN."""
    if p.endswith("EZ") and rnd.random() < 0.85:
        i = max(i for i, c in enumerate(p[:-2]) if c in "AEIOU") if any(c in "AEIOU" for c in p[:-2]) else -1
        if i >= 0:
            p = p[:i] + "ÁÉÍÓÚ"["AEIOU".index(p[i])] + p[i + 1:]
    return p


def _generar_apellido(rnd, origen):
    """Apellido verosímil del origen dado: sílabas típicas (más prefijos y sufijos en los orígenes que los usan)."""
    if origen in ("japones", "chino", "coreano"):
        s = SILABAS[origen]
        return "".join(rnd.choice(s) for _ in range(rnd.choice([1, 2, 2, 3] if origen == "japones" else [1, 1, 2])))
    base_sil = SILABAS.get(origen) or SILABAS["hispano"]
    raiz = "".join(rnd.choice(base_sil) for _ in range(rnd.choice([1, 2, 2, 3])))
    suf = rnd.choice(SUFIJOS_APELLIDO.get(origen) or SUFIJOS_APELLIDO["hispano"])
    if raiz[-1] in "AEIOU" and suf[0] in "AEIOUÁÉÍÓÚ":
        raiz = raiz[:-1]
    p = raiz + suf
    if origen == "hispano":
        p = _acentuar(p, rnd)
    if origen in PREFIJOS_APELLIDO and rnd.random() < 0.18:
        pre = rnd.choice(PREFIJOS_APELLIDO[origen])
        p = (pre + p.capitalize().upper()) if pre.endswith(("'", "-", "_")) else pre + p
    return p


def _generar_nombre(rnd, origen):
    """Nombre verosímil del origen dado: raíz de sílabas típicas más un sufijo de nombre."""
    base_sil = SILABAS.get(origen) or SILABAS["hispano"]
    raiz = "".join(rnd.choice(base_sil) for _ in range(rnd.choice([1, 1, 2])))
    if origen in ("chino", "coreano", "japones"):
        return raiz + ("" if origen == "chino" else rnd.choice(["", "", rnd.choice(base_sil)]))
    suf = rnd.choice(SUFIJOS_NOMBRE.get(origen) or SUFIJOS_NOMBRE["hispano"])
    if raiz[-1] in "AEIOU" and suf[0] in "AEIOUÁÉÍÓÚ":
        raiz = raiz[:-1]
    return raiz + suf


